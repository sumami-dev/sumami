//! Embed the documentation site in the binary.
//!
//! The documentation is a handful of HTML pages and a stylesheet — about 60 KB.
//! Embedding them means a `cargo install sumimi` gives you a server with a
//! documentation site at `/docs`, with nothing else to deploy: no `docs/`
//! directory next to the executable, no CDN, no network.
//!
//! The files live **inside this crate** (`service/docs/`), because `cargo
//! package` only ships what is in the crate directory — a build script that
//! read `../docs` would work in the checkout and produce an empty site in the
//! published crate.
//!
//! The on-disk copy still wins at runtime (see `static_files`): the release
//! archive ships the documentation next to the executable, and a user may have
//! edited it. The embedded copy is the fallback.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// The documentation directory, relative to the crate root.
const DOCS: &str = "docs";

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let docs = root.join(DOCS);

    // Rebuild when a documentation file changes.
    println!("cargo:rerun-if-changed={}", docs.display());

    let mut files = Vec::new();
    collect(&docs, &docs, &mut files);
    files.sort();

    let mut out = String::new();
    out.push_str("// @generated by build.rs — the documentation site, embedded in the binary.\n");
    out.push_str("/// The documentation files: the path (relative to the docs directory) and the bytes.\n");
    out.push_str("pub static DOCS: &[(&str, &[u8])] = &[\n");
    for (name, path) in &files {
        // The path goes into `include_bytes!`, so it has to be a literal.
        let _ = writeln!(
            out,
            "    ({:?}, include_bytes!({:?})),",
            name,
            path.display().to_string()
        );
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("docs.rs"), out).expect("writing the generated docs table");
}

/// Walk the documentation directory, collecting the files.
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(err) => {
            // A missing directory is not an error: the crate still builds, it
            // just has no documentation site in it.
            println!("cargo:warning=no documentation found in {}: {err}", root.display());
            return;
        }
    };

    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }
        let name = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        files.push((name, path));
    }
}
